const fs = require('fs');
const path = require('path');

const INPUT_FILE = './public/books/Prove it Catecishm/Full Text of the Catecism - Children\'s _Prove It_ Catechism.html';
const OUTPUT_FILE = './cloudflare/migrations/0061_seed_prove_it_catechism.sql';

const rawHtml = fs.readFileSync(INPUT_FILE, 'utf-8');

// Regex to capture Q, A, and Reference
// Pattern looks like:
// <p>Q1 Who made you ?</p>
// <p>A GOD.</p>
// <p>Gen 1:27</p>
// Note: Some lines might have extra spaces or dots.
const regex = /<p>Q(\d+)\.?\s*(.*?)<\/p>\s*<p>A\.?\s*(.*?)<\/p>\s*<p>(.*?)<\/p>/gis;

let match;
const items = [];

while ((match = regex.exec(rawHtml)) !== null) {
    const num = parseInt(match[1]);
    const question = match[2].trim();
    const answer = match[3].trim();
    const reference = match[4].trim();

    items.push({ num, question, answer, reference });
}

console.log(`Parsed ${items.length} catechism items.`);

let sql = `-- Migration: Seed 'Prove It' Catechism for Younger Children (Seedling/Sprout)
-- Generated by script

INSERT INTO formations (
    id, title, description,
    formation_type, primary_virtue, context_anchor, cluster_tag,
    min_age_months, max_age_months, duration_minutes,
    liturgical_script, source, sequence_number, is_active
) VALUES 
`;

const values = items.map(item => {
    const id = `liturgy-catechism-prove-it-q${item.num}`;
    const title = `Q${item.num}: ${item.question.replace(/'/g, "''")}`; // Escape quotes
    const description = `Children's Prove It Catechism Question ${item.num}`;
    // Format script with Markdown for bolding
    const script = `**Question:** ${item.question.replace(/'/g, "''")}\n\n**Answer:** ${item.answer.replace(/'/g, "''")}\n\n*${item.reference.replace(/'/g, "''")}*`;

    // Age range: 0 - 5 years (0 - 60 months)
    return `(
        '${id}', 
        '${title}', 
        '${description}', 
        'liturgy', 
        'Wisdom', 
        'Morning_Circle', 
        'catechism', 
        0, 
        60, 
        5, 
        '${script}', 
        'prove_it', 
        ${item.num}, 
        1
    )`;
}).join(',\n');

sql += values + ';\n';

fs.writeFileSync(OUTPUT_FILE, sql);
console.log(`Generated SQL at ${OUTPUT_FILE}`);
